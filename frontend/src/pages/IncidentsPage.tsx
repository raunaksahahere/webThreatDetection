import { useCallback, useEffect, useState } from 'react';
import { Bot, LoaderCircle, Network, RefreshCw, Repeat, Server, ShieldAlert } from 'lucide-react';
import type { CampaignBrief, Incident, IncidentKind } from '../types';
import { createCampaignBrief, errorMessage, getCampaignBrief, listIncidents } from '../api';
import { formatDate, shortId } from '../format';
import { href, reportPath } from '../router';
import { Empty, Notice } from '../components/Section';
import { ClassificationBadge } from '../components/Badges';

const KIND: Record<IncidentKind, { label: string; text: string; Icon: typeof Network }> = {
  campaign: {
    label: 'Campaign link',
    text: 'Different targets share a campaign-specific identifier (payment ID, wallet, phone, e-mail or certificate key).',
    Icon: ShieldAlert,
  },
  shared_infrastructure: {
    label: 'Shared infrastructure',
    text: 'Different targets share only an IP address or domain. Common on shared hosting; weak evidence on its own.',
    Icon: Server,
  },
  repeat_checks: {
    label: 'Repeat checks',
    text: 'The same target was analysed more than once. This is not evidence of a campaign.',
    Icon: Repeat,
  },
};

const ASSESSMENT: Record<string, string> = {
  likely_same_campaign: 'Likely the same campaign',
  possibly_related: 'Possibly related',
  not_enough_evidence: 'Not enough evidence',
  repeat_checks_only: 'Repeat checks only',
};

function BriefView({ b }: { b: CampaignBrief }) {
  if (b.status !== 'ok' && b.status !== 'rejected') {
    return (
      <Notice tone="warn" title={`AI brief ${b.status}`}>
        {b.error ?? 'No brief.'} The deterministic links above are complete without it.
      </Notice>
    );
  }
  return (
    <div className={`brief ${b.status === 'rejected' ? 'brief-rejected' : ''}`}>
      <div className="brief-head">
        <Bot size={16} aria-hidden />
        <strong>AI campaign brief</strong>
        {b.assessment ? <span className="brief-assess">{ASSESSMENT[b.assessment] ?? b.assessment}</span> : null}
        {b.status === 'rejected' ? <span className="brief-flag">Rejected by validation</span> : null}
      </div>
      {b.status === 'rejected' ? (
        <p className="fine">This output broke a grounding rule (see notes) and is shown only for transparency. Rely on the deterministic links.</p>
      ) : null}
      {b.summary ? <p className="brief-summary">{b.summary}</p> : null}
      {b.link_explanations?.length ? (
        <>
          <h4 className="mini-label">How the reports are linked</h4>
          <ul className="brief-list">
            {b.link_explanations.map((l, i) => (
              <li key={i}>
                <code className="mono chip">{l.indicator}</code> {l.explanation}{' '}
                <span className="muted">({l.report_ids.map(shortId).join(', ')})</span>
              </li>
            ))}
          </ul>
        </>
      ) : null}
      {b.common_tactics?.length ? (
        <>
          <h4 className="mini-label">Common tactics (cited findings)</h4>
          <ul className="brief-list">
            {b.common_tactics.map((t, i) => (
              <li key={i}>
                {t.technique}{' '}
                {t.finding_ids.map((f) => (
                  <code key={f} className="mono chip">
                    {f}
                  </code>
                ))}{' '}
                <span className="muted">({t.report_ids.map(shortId).join(', ') || 'no verified report'})</span>
              </li>
            ))}
          </ul>
        </>
      ) : null}
      {b.next_steps?.length ? (
        <>
          <h4 className="mini-label">Suggested next steps</h4>
          <ol className="brief-list">
            {b.next_steps.map((s, i) => (
              <li key={i}>{s}</li>
            ))}
          </ol>
        </>
      ) : null}
      {b.uncertainty ? (
        <p className="fine">
          <strong>Uncertainty:</strong> {b.uncertainty}
        </p>
      ) : null}
      {b.validation_notes?.length ? (
        <details className="brief-notes">
          <summary>Validation notes ({b.validation_notes.length})</summary>
          <ul>
            {b.validation_notes.map((n, i) => (
              <li key={i}>{n}</li>
            ))}
          </ul>
        </details>
      ) : null}
      <p className="fine">
        AI-generated by {b.model ?? 'model'} ({b.provider ?? 'provider'}){b.latency_ms ? `, ${(b.latency_ms / 1000).toFixed(0)} s` : ''}, {formatDate(b.generated_at)}.
        Cited indicators, reports and findings are checked against the cluster; the AI cannot change any classification.
      </p>
    </div>
  );
}

function IncidentCard({ c }: { c: Incident }) {
  const kind = KIND[c.kind ?? 'campaign'];
  const [brief, setBrief] = useState<CampaignBrief | null>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    if (c.has_brief) getCampaignBrief(c.cluster_id).then(setBrief).catch(() => undefined);
  }, [c.cluster_id, c.has_brief]);

  const generate = async () => {
    setBusy(true);
    setErr(null);
    try {
      setBrief(await createCampaignBrief(c.cluster_id));
    } catch (e) {
      setErr(errorMessage(e));
    } finally {
      setBusy(false);
    }
  };

  return (
    <li className={`incident incident-${c.kind ?? 'campaign'}`}>
      <div className="incident-head">
        <kind.Icon size={18} aria-hidden />
        <span className="incident-kind">{kind.label}</span>
        <code className="mono incident-id">{c.cluster_id}</code>
        <span className="count-tag">
          {c.report_ids.length} reports · {c.distinct_targets ?? '?'} {c.distinct_targets === 1 ? 'target' : 'targets'}
        </span>
      </div>
      <p className="fine incident-kind-text">{kind.text}</p>
      {c.classifications?.length ? (
        <div className="incident-cls">
          {c.classifications.map((k) => (
            <ClassificationBadge key={k} value={k} size="sm" />
          ))}
        </div>
      ) : null}
      <div className="incident-span">
        <span>
          <span className="mini-label">First seen</span> {formatDate(c.first_seen)}
        </span>
        <span>
          <span className="mini-label">Last seen</span> {formatDate(c.last_seen)}
        </span>
      </div>
      <div>
        <span className="mini-label">Shared evidence</span>
        <ul className="shared-list">
          {c.shared.map((s, i) => (
            <li key={i} className="mono">
              {s}
            </li>
          ))}
        </ul>
      </div>
      {c.reports?.length ? (
        <ul className="incident-targets">
          {c.reports.map((r) => (
            <li key={r.id}>
              <a className="report-pill mono" href={href(reportPath(r.id))}>
                {shortId(r.id)}
              </a>
              {r.classification ? <ClassificationBadge value={r.classification} size="sm" /> : null}
              <span className="incident-target-text">{r.target}</span>
            </li>
          ))}
        </ul>
      ) : (
        <div className="incident-reports">
          {c.report_ids.map((rid) => (
            <a key={rid} className="report-pill mono" href={href(reportPath(rid))}>
              {shortId(rid)}
            </a>
          ))}
        </div>
      )}
      {c.kind !== 'repeat_checks' ? (
        <div className="brief-actions">
          <button type="button" className="btn btn-secondary" onClick={() => void generate()} disabled={busy}>
            {busy ? <LoaderCircle size={15} className="spin" aria-hidden /> : <Bot size={15} aria-hidden />}
            {busy ? 'Generating brief (free/local model, up to ~90 s)…' : brief ? 'Regenerate AI campaign brief' : 'Generate AI campaign brief'}
          </button>
        </div>
      ) : null}
      {err ? (
        <Notice tone="bad" title="Brief failed">
          {err}
        </Notice>
      ) : null}
      {brief ? <BriefView b={brief} /> : null}
    </li>
  );
}

export function IncidentsPage() {
  const [items, setItems] = useState<Incident[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [showRepeats, setShowRepeats] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      setItems(await listIncidents());
      setError(null);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  const visible = (items ?? []).filter((c) => showRepeats || c.kind !== 'repeat_checks');
  const repeats = (items ?? []).filter((c) => c.kind === 'repeat_checks').length;

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <p className="eyebrow">Campaign board</p>
          <h1 className="page-title">Incidents</h1>
          <p className="page-lede">
            Reports grouped deterministically because they share indicators. Each group says what the link actually means; an optional AI brief explains it using only that evidence.
          </p>
        </div>
        <button type="button" className="btn btn-secondary" onClick={() => void load()} disabled={loading}>
          {loading ? <LoaderCircle size={15} className="spin" aria-hidden /> : <RefreshCw size={15} aria-hidden />} Refresh
        </button>
      </div>
      {error ? (
        <Notice tone="bad" title="Could not load incidents">
          {error}
        </Notice>
      ) : null}
      {items === null && !error ? <div className="skeleton-table" aria-busy="true" aria-label="Loading" /> : null}
      {items && repeats > 0 ? (
        <label className="check repeats-toggle">
          <input type="checkbox" checked={showRepeats} onChange={(e) => setShowRepeats(e.target.checked)} />
          <span>Show {repeats} repeat-check groups (same target analysed again)</span>
        </label>
      ) : null}
      {items && visible.length === 0 ? <Empty>No incident clusters yet. Clusters appear when two or more different reports share evidence.</Empty> : null}
      {visible.length > 0 ? (
        <ul className="incidents">
          {visible.map((c) => (
            <IncidentCard key={c.cluster_id} c={c} />
          ))}
        </ul>
      ) : null}
    </div>
  );
}
